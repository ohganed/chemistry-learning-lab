import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const html=readFileSync(new URL('../equilibrium-experiment.html',import.meta.url),'utf8');
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(js,'Inline simulation script exists');
new vm.Script(js,{filename:'equilibrium-experiment-inline.js'});
const math=js.match(/function cA\(t\)\{[\s\S]*?\}\nfunction draw/);
assert.ok(math,'Concentration model function exists');
const body=math[0].slice(0,-'\nfunction draw'.length);
const values={kf:0.6,kr:0.3,catalyst:1,initial:100};
const sandbox={value:key=>values[key],Math};
vm.createContext(sandbox);
vm.runInContext(body,sandbox);
const approx=(x,y,msg)=>assert.ok(Math.abs(x-y)<1e-8,msg+': '+x+' vs '+y);
approx(sandbox.cA(0),1,'Initial concentration');
approx(sandbox.cA(100),1/3,'Equilibrium concentration');
const k=values.kf/values.kr;
approx((1-sandbox.cA(100))/sandbox.cA(100),k,'Equilibrium ratio K=kf/kr');
const reference=sandbox.cA(2);
values.catalyst=3;
assert.ok(sandbox.cA(2)<reference,'Increasing catalytic rate multiplier approaches equilibrium faster');
approx(sandbox.cA(100),1/3,'Catalyst does not shift equilibrium');
values.initial=0;
approx(sandbox.cA(0),0,'All B initial condition');
approx(sandbox.cA(100),1/3,'Convergence independent of initial composition');
values.initial=100;values.kf=0.3;values.kr=0.6;values.catalyst=1;
approx(sandbox.cA(100),2/3,'Reversing rate ratio changes equilibrium appropriately');
console.log('PASS: first-order reversible reaction model, equilibrium ratio and catalyst invariance.');
